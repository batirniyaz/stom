"""Расшифровка речи врача — через наш сервер, а не через браузер.

ЗАЧЕМ СВОЙ ПУТЬ. Голосовой ввод вопроса сначала был сделан браузерным
`SpeechRecognition`. Он работает, но у него две беды, из-за которых его
нельзя оставлять единственным:

1. Он есть только в Chrome. В Firefox и в Safari кнопка микрофона просто
   исчезала, то есть функция была у половины пользователей.
2. Звук он всё равно отправляет в облако Google, но МИМО НАС: мы не знаем,
   что ушло, не можем это записать в журнал и не можем сменить провайдера.

Через свой эндпойнт оба пункта закрываются: путь один для всех браузеров, и
решение «куда отправлять звук» принимаем мы.

ЧТО ОТПРАВЛЯЕТСЯ. Только звук и короткая инструкция. Ни находок, ни ФИО, ни
номера карты — расшифровщику они не нужны, а значит и уходить не должны.

ФОРМАТ. Принимаем WAV. Это не каприз: Gemini перечисляет поддерживаемые
типы звука (wav, mp3, aiff, aac, ogg, flac), и `audio/webm`, который пишет
`MediaRecorder` в Chrome, в этот список НЕ входит. Конвертировать на сервере
значило бы требовать ffmpeg на машине клиники; вместо этого браузер пишет
сырой PCM через Web Audio и сам складывает WAV — это двадцать строк и ноль
зависимостей.
"""
from __future__ import annotations

import base64

import case_chat

# Модели те же, что у чата, и по той же причине: ключ в проекте уже есть.
# Порядок — от более новой к запасным: если первая недоступна в регионе или
# перегружена, расшифровка не должна отваливаться совсем.
MODELS = ("gemini-3.8-flash", "gemini-flash-lite-latest", "gemini-2.5-flash-lite")

# Инструкция намеренно жёсткая. Модель охотно «улучшает» речь: дописывает
# вежливость, исправляет номера зубов на правдоподобные, добавляет вводные.
# Врачу нужна ЕГО фраза, а не пересказ.
PROMPT = (
    "Расшифруй речь дословно. Язык — русский, возможны стоматологические "
    "термины и номера зубов (например «сорок шестой», «тринадцатый»). "
    "Верни ТОЛЬКО расшифрованный текст, без кавычек, без пояснений, без "
    "описания звука. Ничего не добавляй от себя и не исправляй сказанное. "
    "Если речи нет или она неразборчива — верни пустую строку."
)

# 20 МБ — предел на весь запрос у Gemini; держим запас и режем раньше, чтобы
# ошибка приходила от нас с понятным текстом, а не отказом провайдера.
MAX_BYTES = 8 * 1024 * 1024


def transcribe(audio: bytes, mime: str = "audio/wav") -> tuple[str, str]:
    """Расшифровать запись. Возвращает (текст, имя модели).

    Исключение — только на отсутствие ключа и на отказ всех моделей: в
    остальном пустая расшифровка это нормальный ответ (врач нажал и
    промолчал), и ошибкой её делать нельзя.
    """
    if not audio:
        return "", ""
    if len(audio) > MAX_BYTES:
        raise RuntimeError(
            f"запись длиннее допустимого ({len(audio) // 1024} КБ при пределе "
            f"{MAX_BYTES // 1024} КБ). Вопрос голосом — это одна-две фразы.")

    key = (case_chat._read_key("GEMINI_API_KEY")
           or case_chat._read_key("STOMADENT_LLM_KEY"))
    if not key:
        raise RuntimeError(
            "нет ключа для расшифровки речи: положите GEMINI_API_KEY в "
            "data/secrets.env (файл вне гита).")

    body = {
        "contents": [{"parts": [
            {"text": PROMPT},
            {"inline_data": {"mime_type": mime,
                             "data": base64.b64encode(audio).decode("ascii")}},
        ]}],
        # Температура ноль: расшифровка это не творческая задача, и разброс
        # здесь означает только то, что одну и ту же фразу распознают
        # по-разному.
        "generationConfig": {"temperature": 0, "maxOutputTokens": 400},
    }

    problems = []
    for model in MODELS:
        try:
            data = case_chat._post(
                "https://generativelanguage.googleapis.com/v1beta/models/"
                f"{model}:generateContent?key={key}",
                body, {"content-type": "application/json"})
            parts = (((data.get("candidates") or [{}])[0]
                      .get("content") or {}).get("parts") or [])
            text = "".join(p.get("text", "") for p in parts).strip()
            # Модель иногда всё же оборачивает ответ в кавычки — снимаем их,
            # иначе они попадут в поле вопроса.
            if len(text) > 1 and text[0] in "«\"'" and text[-1] in "»\"'":
                text = text[1:-1].strip()
            return text, model
        except Exception as exc:                            # noqa: BLE001
            problems.append(f"{model}: {type(exc).__name__} {exc}")
    raise RuntimeError("расшифровка не удалась — " + "; ".join(problems))
