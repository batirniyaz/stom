"""Вырезать панораму из отчётной распечатки Dentium.

Клиника присылает не сам снимок, а страницу отчёта: шапка с фамилией и
датой, рамка, снимок, поле «Комментарии». Для разметки и обучения нужен
только снимок — и без шапки: в ней имя пациента.

КАК БЫЛО И ПОЧЕМУ ЭТО ЛОМАЛОСЬ. Прежнее правило искало «жирные чёрные
линии рамки» — строки, тёмные на 80% ширины, — и брало первую такую ниже
65% высоты страницы. Но такие строки есть и ВНУТРИ самой панорамы, под
нижней челюстью. На 12 отчётах из 13 срез проходил по корням нижних
зубов: снимок занимает строки 355-2272, а оставалось около 1400 строк.
Врач размечал снимки без нижней челюсти, и очаг у нижнего зуба увидеть
было невозможно. Снимок не из отчёта правило тоже резало: у панорамы из
карточки пациента пропадали верхние 280 строк.

КАК СТАЛО. Фон отчёта — белый, а в рентгене чисто белых пикселей почти
нет. Снимок — это самая длинная полоса строк, где белого меньше 30%, а
внутри неё — самая длинная полоса таких же столбцов. Проверено на всех 13
отчётах: у 12 рамка одна и та же (35, 355, 3265, 2272), у детского
снимка панорама меньше и с белыми полями — (35, 519, 3265, 2108), и это
тоже верно. На снимках DENTEX и на панораме из карточки полоса занимает
98-100% высоты — отчёта нет, и ничего не режется.

Правило идемпотентно: у уже вырезанного снимка полоса — весь кадр.
"""
from __future__ import annotations

import cv2
import numpy as np

WHITE = 235            # «белый фон отчёта»
WHITE_FRAC = 0.3       # строка снимка: белого меньше этой доли
REPORT_MAX_FRAC = 0.9  # полоса короче — значит, вокруг шаблон отчёта


def _longest_run(mask: np.ndarray) -> tuple[int, int]:
    best, start = (0, 0), None
    for i, v in enumerate(list(mask) + [False]):
        if v and start is None:
            start = i
        elif not v and start is not None:
            if i - start > best[1] - best[0]:
                best = (start, i)
            start = None
    return best


def xray_region(img: np.ndarray) -> tuple[int, int, int, int] | None:
    """(x1, y1, x2, y2) панорамы внутри отчёта или None, если отчёта нет."""
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if img.ndim == 3 else img
    h, w = gray.shape
    white = gray > WHITE
    y1, y2 = _longest_run(white.mean(axis=1) < WHITE_FRAC)
    if y2 - y1 <= 0:
        return None
    x1, x2 = _longest_run(white[y1:y2].mean(axis=0) < WHITE_FRAC)
    if (y2 - y1) >= REPORT_MAX_FRAC * h and (x2 - x1) >= REPORT_MAX_FRAC * w:
        return None
    # Слишком маленькая полоса — это не снимок, а что-то в шаблоне.
    if (y2 - y1) < 0.3 * h or (x2 - x1) < 0.5 * w:
        return None
    return int(x1), int(y1), int(x2), int(y2)


def crop_report(img: np.ndarray) -> np.ndarray:
    """Снимок без шаблона отчёта; снимок не из отчёта возвращается как есть."""
    box = xray_region(img)
    if box is None:
        return img
    x1, y1, x2, y2 = box
    return img[y1:y2, x1:x2]
