"""Кому адресована находка: единый справочник ролей и их порядка.

Один список на все источники — КЛКТ (`cbct_findings`), карту контактов
(`ios_occlusion_map`) и находки по скану (`ios_findings`). Держать по копии в
каждом модуле нельзя: они уже начали расходиться (у одного «Ручная проверка
снимка», у другого «скана»; пародонтолог заведён под двумя ключами), а врач
получает один список — и половина находок уехала бы в чужой раздел. Это та же
ловушка, что с `wbf()` в трёх местах.

Порядок — клинический, а не технический: пока не снято воспаление, ни лечить,
ни протезировать нельзя. Он взят из реального плана клиники, см.
`cbct_plan.STAGES` и заметку про порядок этапов в CLAUDE.md.

Модуль намеренно пустой по зависимостям: его импортируют и лёгкие скрипты, и
тяжёлые, которые тянут torch или nnU-Net.
"""

ROUTES = {
    "urgent":  ("Неотложная помощь", 0),
    "hygiene": ("Гигиенист / пародонтолог", 1),
    "surgery": ("Хирург", 2),
    "therapy": ("Терапевт / эндодонт", 3),
    "gnatho":  ("Гнатолог (диагностика окклюзии)", 4),
    "ortho":   ("Ортодонт", 5),
    "prostho": ("Ортопед (протезирование, имплантация)", 6),
    "review":  ("Ручная проверка", 9),
}


def route_list(keys=None) -> list:
    """Роли для выдачи в API: [{key, label, order}], в клиническом порядке.

    keys — оставить только эти роли (обычно те, что реально встретились в
    находках); None — отдать все.
    """
    items = ROUTES.items() if keys is None else (
        (k, ROUTES[k]) for k in ROUTES if k in set(keys))
    return [{"key": k, "label": label, "order": order}
            for k, (label, order) in sorted(items, key=lambda kv: kv[1][1])]


def label(key: str) -> str:
    return ROUTES.get(key, (key, 8))[0]


def order(key: str) -> int:
    return ROUTES.get(key, (key, 8))[1]


# ------------------------------------------------------- уровни критичности

# ТРИ уровня, решение команды 17.11: от пяти и от буквенной шкалы A+…C
# отказались — врачам неудобно.
#
# Таблица лежит здесь, а не в трёх местах, по той же причине, что ROUTES выше:
# слово из неё стоит на бейдже находки, в карточке, в подписи зуба в 3D, в
# обоих PDF и в сводке чата. Разъехавшиеся копии дали бы «Важная» в
# интерфейсе и «Средняя» в отчёте под одной и той же находкой.
#
# Своего поля у находок нет и не нужно: `severity` уже имеет ровно три
# значения, перевод один к одному.
#
# Цвета — ровно три, без оранжевого (прямая просьба: оранжевый читается как
# «почти красный» и путает с критичным).
LEVELS = {
    "alert":   ("Критичная", "Крит", "#e05252",
                "требует внимания в первую очередь", 0),
    "warning": ("Важная", "Важн", "#d6a327",
                "нужно лечение или решение врача", 1),
    "info":    ("Незначительная", "Незнач", "#8b9099",
                "вариант нормы, учесть и наблюдать", 2),
}

# Чего в таблице нет, то НЕ становится «незначительным». Неизвестное
# severity — это ошибка в коде, и подставлять вместо него нижний уровень
# опаснее всего: критичная находка молча прочиталась бы как норма. Поэтому
# отдельный уровень с честной подписью, и он идёт ПЕРВЫМ в списке, чтобы
# такая находка бросалась в глаза, а не тонула в конце ленты.
LEVEL_UNKNOWN = ("Уровень не определён", "?", "#b06ccc",
                 "сбой в расчёте находки, нужна ручная проверка", -1)


def level_of(severity: str | None) -> dict:
    """Уровень критичности для выдачи в API: {key, label, short, color, ...}."""
    label_, short, color, meaning, order_ = LEVELS.get(
        str(severity or ""), LEVEL_UNKNOWN)
    return {"key": str(severity or "") if severity in LEVELS else "unknown",
            "label": label_, "short": short, "color": color,
            "meaning": meaning, "order": order_}


def level_list() -> list:
    """Все уровни в порядке убывания важности — для легенды и фильтров."""
    return [level_of(k) for k in sorted(LEVELS, key=lambda k: LEVELS[k][4])]


# Надёжность находки. СЛОВОМ, а не процентом — и это решение, не недоделка:
# находки считаются геометрией по маске, вероятности у них нет, и процент
# пришлось бы выдумать (см. CLAUDE.md, «Основание находки, а НЕ процент
# уверенности»). Категорию ставит правило находки: она говорит, насколько
# надёжно САМО ИЗМЕРЕНИЕ, а не насколько вероятна болезнь.
#
# Измеренный процент у нас есть, но он про другой слой — точность
# сегментации зубов на внешней выборке (96.9%, 95% ДИ 96.2–97.6, 100
# пациентов). Он показывается отдельной строкой про систему, а не на
# карточке находки, иначе читался бы как «вероятность диагноза 96.9%».
CONFIDENCE = {
    "high":   ("высокая", "измерение прямое, запас до порога большой"),
    "medium": ("средняя", "измерение косвенное или близко к порогу"),
    "low":    ("низкая", "маска ненадёжна, значение показано как ориентир"),
}


def confidence_of(conf: str | None) -> dict:
    """{key, label, note} для карточки и отчёта. Неизвестное — не прячем."""
    label_, note = CONFIDENCE.get(
        str(conf or ""), ("не определена", "правило не указало надёжность"))
    return {"key": str(conf or "") if conf in CONFIDENCE else "unknown",
            "label": label_, "note": note}


def level_rgb(key: str | None) -> tuple:
    """Цвет уровня для PDF: reportlab принимает доли 0..1, а не #hex.

    Пересчёт из той же строки, что уходит на фронт. Отдельная таблица
    «цвета для печати» разъехалась бы с экраном на первой же правке — в
    отчёте по КЛКТ это уже было: там `info` рисовался СИНИМ, тогда как на
    экране он серый, и врач читал бумагу иначе, чем снимок.
    """
    h = level_of(key)["color"].lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


# Уровень словами ДЛЯ ПАЦИЕНТА. То же деление, другой язык: «критичная
# находка» пациенту ничего не говорит, а «требует срочного внимания» —
# говорит. Решение из спеки §6; держим рядом с самой шкалой, иначе отчёт
# пациенту и отчёт врачу разойдутся в смысле уровней.
LEVEL_FOR_PATIENT = {
    "alert": "требует срочного внимания",
    "warning": "нужно лечение",
    "info": "для сведения",
}


def level_patient(key: str | None) -> str:
    return LEVEL_FOR_PATIENT.get(str(key or ""), "нужна проверка врачом")
