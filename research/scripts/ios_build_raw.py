# Порог «это шов, а не тёмная ткань». Швы атласа заливаются ровным чёрным
# (максимум канала < 20), а самая тёмная реальная ткань на скане — тень между
# зубами, и она не опускается ниже 30 даже в глубоких фиссурах.
ATLAS_GAP_MAX = 20


# На сколько пикселей ужимать UV-треугольник внутрь своего фрагмента.
# Полтора пикселя: билинейная выборка берёт максимум по одному текселю в
# каждую сторону, плюс запас на округление.
#
# ВЫКЛЮЧЕНО (0). Приём вводился против красных крапин на зубах, но настоящей
# причиной оказалась лишняя инверсия V (см. ниже по файлу). После её
# устранения ужатие только вредит: фрагменты атласа сняты разными кадрами с
# разной экспозицией, и однотонный треугольник делает эту разницу видимой —
# зуб покрывается пятнами оттенков. Без ужатия градиент внутри фрагмента
# сглаживает стык. Оставлено как рабочий инструмент на случай атласа с
# по-настоящему слипшимися фрагментами.
UV_INSET_PX = 0.0


def _inset_uv(verts, faces, uv, tex_size):
    """Ужать каждый UV-треугольник к его центру — иначе цвет течёт от соседа.

    ЗАЧЕМ. Текстура интраорального сканера это не несколько больших кусков, а
    мозаика по ОДНОМУ квадратику на треугольник. Замер на клиническом скане
    (273 382 треугольника): медианный фрагмент 20.9 px², сторона около 6.5
    пикселей; 56% фрагментов мельче 25 px². Фрагменты лежат вплотную, полей
    между ними нет.

    При таком размере выборка у края треугольника физически захватывает
    соседний фрагмент — а соседний в атласе может быть куском десны, тогда
    как сам треугольник лежит на зубе. Отсюда красные крапины на эмали,
    которые врач и просил убрать.

    Что уже проверено и НЕ работает: точечная выборка (крапины остаются —
    промах идёт от самой координаты, а не от усреднения), отключение
    мипмапов, заливка чёрных швов (она лечит другое — попадание в пустоту, а
    не в чужой фрагмент).

    Цена приёма: у каждого треугольника должны быть СВОИ вершины, поэтому их
    число утраивается. Геометрия при этом не меняется ни на микрон —
    дублируются координаты, а не сдвигаются.
    """
    import numpy as np
    w, h = tex_size
    tri = uv[faces].astype(np.float64)            # (F, 3, 2) в долях
    px = tri * np.array([w, h])                   # в пикселях
    c = px.mean(axis=1, keepdims=True)
    d = px - c
    # Насколько ужать: на UV_INSET_PX, но не больше 35% размера фрагмента,
    # иначе у самых мелких треугольников выборка схлопнется в точку.
    r = np.linalg.norm(d, axis=2, keepdims=True)
    r = np.maximum(r, 1e-9)
    shrink = np.minimum(UV_INSET_PX / r, 0.35)
    px = c + d * (1.0 - shrink)
    uv_out = (px / np.array([w, h])).reshape(-1, 2)
    verts_out = verts[faces].reshape(-1, 3)
    faces_out = np.arange(len(uv_out), dtype=np.int64).reshape(-1, 3)
    return verts_out, faces_out, uv_out


# Сколько раз усреднить цвет вершины с соседями по ребру.
# Один проход. Два уже стирают рисунок эмали и превращают зуб в пластик —
# проверено на клиническом скане; врачу нужен реальный вид, а не стилизация.
COLOR_SMOOTH_ITERS = 1


def _face_average_colors(tex_arr, uv, faces, samples=6):
    """Цвет вершины = среднее по ПЛОЩАДИ её фрагментов атласа.

    ЗАЧЕМ ИМЕННО ТАК. Развёртка сканера мелкая: медианный UV-треугольник имеет
    сторону 7.9 пикселя. Если брать по ОДНОМУ текселю на вершину (как делалось
    раньше), выборка попадает в случайную точку такого квадратика, соседние
    вершины берут случайные точки соседних квадратиков — и модель покрывается
    мозаикой, хотя сама текстура гладкая. Это не ошибка координат: сверка с
    исходным OBJ показала, что 86% «зубных» вершин честно получают светлый
    цвет. Шумит именно выборка.

    Мипмапы во вьюере эту болезнь не лечат — проверено: они усредняют по
    экранному пикселю, а разброс сидит в самих данных вершины.

    Среднее по треугольнику берёт весь фрагмент целиком (около 64 текселей),
    поэтому случайность гасится, а настоящий цвет и рисунок сохраняются.
    Вершина усредняется по всем своим треугольникам — граница между зубом и
    десной от этого не размывается: там перепад большой и держится на многих
    треугольниках подряд.
    """
    import numpy as np
    h, w = tex_arr.shape[:2]
    tri = uv[faces]                                   # (F, 3, 2)
    # Барицентрическая сетка внутри треугольника: равномерные точки без краёв,
    # чтобы не зацепить соседний фрагмент.
    pts = []
    for i in range(samples):
        for j in range(samples - i):
            a = (i + 0.5) / samples
            b = (j + 0.5) / samples
            if a + b < 1.0:
                pts.append((a, b))
    pts = np.array(pts, dtype=np.float64)
    acc = np.zeros((len(faces), 3), dtype=np.float64)
    for a, b in pts:
        c = 1.0 - a - b
        p = tri[:, 0] * a + tri[:, 1] * b + tri[:, 2] * c
        px = np.clip((p[:, 0] * (w - 1)).astype(np.int32), 0, w - 1)
        py = np.clip(((1.0 - p[:, 1]) * (h - 1)).astype(np.int32), 0, h - 1)
        acc += tex_arr[py, px]
    face_col = acc / len(pts)

    # Раскладываем цвет граней по вершинам (каждая вершина — среднее своих).
    n = int(faces.max()) + 1
    out = np.zeros((n, 3), dtype=np.float64)
    cnt = np.zeros(n, dtype=np.float64)
    for k in range(3):
        idx = faces[:, k]
        for ch in range(3):
            out[:, ch] += np.bincount(idx, weights=face_col[:, ch], minlength=n)
        cnt += np.bincount(idx, minlength=n)
    cnt[cnt == 0] = 1.0
    return np.clip(np.round(out / cnt[:, None]), 0, 255).astype(np.uint8)


SHADING_ITERS = 40        # радиус «локальной яркости», в проходах по рёбрам
SHADING_STRENGTH = 0.85   # насколько выравнивать: 1.0 — полностью


def _flatten_shading(colors, faces, n_verts,
                     iters=SHADING_ITERS, strength=SHADING_STRENGTH):
    """Убрать неравномерность подсветки, сохранив цвет и рисунок.

    ЗАЧЕМ. Врач видел на скане «паутину» светлых прожилок — и по десне, и по
    зубам. Это НЕ шум выборки и не скачки между кадрами: замер показал, что
    разница цвета у соседних вершин мала (медиана 3.3 из 441, у 90% рёбер
    меньше 10). Прожилки ПЛАВНЫЕ, они накапливаются на расстоянии в десятки
    вершин — поэтому их не берут ни усреднение по соседям, ни билатеральный
    фильтр: локально всё гладко.

    Природа их такая: сканер снимает вспышкой в упор, и на каждом кадре
    выпуклости освещены сильнее впадин. Атлас склеен из сотен таких кадров, и
    по поверхности гуляет медленная волна яркости.

    Приём стандартный для неравномерной подсветки: считаем ЛОКАЛЬНУЮ яркость
    (сильно размытая копия) и делим на неё. Медленная волна уходит, а всё,
    что мельче радиуса размытия — рисунок эмали, границы, блики — остаётся,
    потому что делится само на себя.

    `strength` < 1 оставляет часть затенения: полностью плоская картинка
    читается как аппликация, а врачу нужен объём.
    """
    import numpy as np
    if iters <= 0:
        return colors
    c = colors.astype(np.float64)
    lum = c.mean(axis=1)
    e = np.vstack([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    e = np.vstack([e, e[:, ::-1]])
    a, b = e[:, 0], e[:, 1]
    deg = np.bincount(a, minlength=n_verts).astype(np.float64)
    deg[deg == 0] = 1.0
    blur = lum.copy()
    for _ in range(iters):
        blur = 0.5 * blur + 0.5 * (np.bincount(a, weights=blur[b],
                                               minlength=n_verts) / deg)
    target = float(np.median(blur))
    blur = np.maximum(blur, 1.0)
    gain = (target / blur) ** strength
    # Ограничиваем усиление: в глубокой тени деление вытянуло бы шум.
    gain = np.clip(gain, 0.6, 1.7)
    out = c * gain[:, None]
    return np.clip(np.round(out), 0, 255).astype(np.uint8)


BILATERAL_ITERS = 10
BILATERAL_SIGMA = 12.0        # порог «свой/чужой» по цвету, в единицах 0-255


def _bilateral_colors(colors, faces, n_verts,
                      iters=BILATERAL_ITERS, sigma=BILATERAL_SIGMA):
    """Убрать скачки яркости между кадрами, НЕ размывая границы тканей.

    ЗАЧЕМ ИМЕННО БИЛАТЕРАЛЬНЫЙ, а не обычное усреднение. Текстура сканера —
    мозаика из сотен независимых квадратиков, каждый снят своим кадром со
    своей вспышкой (видно, если открыть сам атлас: зуб и десна лежат
    вперемешку кусками по 150-300 пикселей). Внутри квадратика цвет гладкий,
    а на стыке — скачок яркости. Стыки образуют сетку по всей поверхности,
    и именно её врач видел как «крапинку» на десне.

    Обычное усреднение по соседям эту сетку снимает только за много проходов,
    а за много проходов оно стирает и границу эмаль/десна, и рисунок зуба —
    проверено, два прохода уже превращают зуб в пластик.

    Билатеральный фильтр усредняет вершину ТОЛЬКО с теми соседями, чей цвет
    близок: скачок между кадрами (обычно 10-30 единиц) сглаживается, а
    переход зуб-десна (больше сотни) остаётся резким, потому что соседи по ту
    сторону границы в среднее почти не попадают.
    """
    import numpy as np
    if iters <= 0:
        return colors
    e = np.vstack([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    e = np.vstack([e, e[:, ::-1]])
    a, b = e[:, 0], e[:, 1]
    c = colors.astype(np.float64)
    inv2s2 = 1.0 / (2.0 * sigma * sigma)
    for _ in range(iters):
        d2 = ((c[a] - c[b]) ** 2).sum(axis=1)
        wgt = np.exp(-d2 * inv2s2)
        num = np.zeros_like(c)
        for ch in range(3):
            num[:, ch] = np.bincount(a, weights=wgt * c[b, ch],
                                     minlength=n_verts)
        den = np.bincount(a, weights=wgt, minlength=n_verts)
        # Вершина всегда участвует в собственном среднем с весом 1 — иначе
        # изолированная точка потеряла бы свой цвет целиком.
        num += c
        den += 1.0
        c = num / den[:, None]
    return np.clip(np.round(c), 0, 255).astype(np.uint8)


def _smooth_vertex_colors(colors, faces, n_verts, iters=COLOR_SMOOTH_ITERS):
    """Усреднить цвет по соседям на СЕТКЕ, а не в текстуре.

    ЗАЧЕМ. Атлас интраорального сканера — не непрерывная развёртка, а набор
    отдельных кадров съёмки. Замер на клиническом скане: участок поверхности
    размером 3 мм разбросан по атласу на 4350 x 4391 пикселей и попадает в
    38-77 разных блоков. Соседние по поверхности треугольники берут цвет из
    РАЗНЫХ кадров, снятых под своим углом и со своей экспозицией, — и зуб
    покрывается мозаикой оттенков, хотя в самом атласе он гладкий кремовый.

    Разница между кадрами — шум съёмки, а не свойство зуба, поэтому её
    правильно снимать усреднением. Усредняем по РЁБРАМ СЕТКИ: там соседи
    действительно рядом на поверхности. В текстуре соседний тексель может
    принадлежать другому кадру, поэтому сглаживание атласа не годится.

    Что при этом НЕ теряется: граница эмали и десны переживает усреднение,
    потому что перепад там большой и держится на множестве вершин подряд,
    тогда как разница экспозиций мелкая и случайная по знаку.
    """
    import numpy as np
    if iters <= 0:
        return colors
    e = np.vstack([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    e = np.vstack([e, e[:, ::-1]])
    deg = np.bincount(e[:, 0], minlength=n_verts).astype(np.float64)
    deg[deg == 0] = 1.0
    c = colors.astype(np.float64)
    for _ in range(iters):
        acc = np.zeros_like(c)
        for k in range(3):
            acc[:, k] = np.bincount(e[:, 0], weights=c[e[:, 1], k],
                                    minlength=n_verts)
        nb = acc / deg[:, None]
        # Половина своего цвета, половина соседского: полное замещение за две
        # итерации уже заметно размывает рисунок эмали.
        c = 0.45 * c + 0.55 * nb
    return np.clip(np.round(c), 0, 255).astype(np.uint8)


def _fill_atlas_gaps(tex):
    """Залить чёрные швы атласа цветом ближайшего фрагмента.

    ЗАЧЕМ. Текстура сканера — атлас из фотографических кусков, разделённых
    чёрными промежутками (замер: 4.6% площади). Замер по готовой модели:
    в эти промежутки попадает 2.4% вершин верхней челюсти и 3.1% нижней.
    На розовой десне чёрная точка теряется, а на светлом зубе она читается
    как грязная красная крапина — ровно то, на что жаловался врач, когда
    просил «оригинальный цвет без красок».

    Ни точечная выборка, ни отключение мипмапов этого не убирают: дело не в
    фильтрации, а в том, что вершина честно указывает в пустое место атласа.

    Лечится заливкой промежутков цветом ближайшего непустого пикселя — это
    стандартный приём (edge padding), он не меняет ни одного пикселя внутри
    фрагментов, то есть оригинальный цвет остаётся нетронутым.
    """
    import numpy as np
    from PIL import Image
    from scipy import ndimage as ndi

    a = np.asarray(tex.convert("RGB"))
    gap = a.max(axis=2) < ATLAS_GAP_MAX
    if not gap.any():
        return tex
    # Индексы ближайшего НЕпустого пикселя для каждого пустого.
    _, (iy, ix) = ndi.distance_transform_edt(gap, return_indices=True)
    out = a.copy()
    out[gap] = a[iy[gap], ix[gap]]
    print(f"   швы атласа: залито {gap.mean()*100:.1f}% площади")
    return Image.fromarray(out)


def load_jaw(path: Path, baked: bool = False, fill_gaps: bool = False):
    """Скан с РОДНОЙ текстурой (по умолчанию) или с цветом в вершинах.

    Текстура даёт то, что врач называет оригиналом: налёт, пигментацию,
    границы реставраций. Вершинный цвет их теряет — деталей в нём столько же,
    сколько вершин, а после упрощения до 70 тыс. это в десятки раз грубее
    исходных 6348x6008.

    Полную текстуру в GLB класть по-прежнему нельзя (22.8 МБ на две челюсти),
    поэтому она уменьшается до TEX_SIDE. При `baked=True` остаётся прежнее
    поведение — на случай, если браузер не потянет текстуру.

    Швы развёртки: при текстуре вершины НЕ сливаются и геометрия НЕ
    упрощается. Слияние по координатам убивает UV (одна точка на шве имеет
    две разные координаты текстуры), а упрощение рвёт сетку по швам — на
    модели это выглядело как чёрные трещины по десне.
    """
    from scipy.spatial import cKDTree
    m = trimesh.load(str(path), process=False, force="mesh")
    vis = m.visual
    img = getattr(getattr(vis, "material", None), "image", None)
    verts = np.asarray(m.vertices, np.float64)
    faces = np.asarray(m.faces)

    if not baked and img is not None and vis.uv is not None:
        # ---- РОДНАЯ ТЕКСТУРА СКАНЕРА, ПО ВОЗМОЖНОСТИ НЕТРОНУТОЙ ----
        #
        # Врач просит «оригинал», и это надо понимать буквально: любая наша
        # правка пикселей отдаляет от него. Поэтому по умолчанию текстура
        # уходит в GLB теми же байтами, что лежат в файле сканера.
        from PIL import Image
        touched = False
        tex = img

        if max(tex.size) > TEX_MAX_SIDE:
            k = TEX_MAX_SIDE / max(tex.size)
            tex = tex.convert("RGB").resize(
                (max(int(tex.width * k), 1), max(int(tex.height * k), 1)),
                Image.LANCZOS)
            touched = True

        if fill_gaps:
            # Заливка пустот атласа. НЕ по умолчанию: она меняет пиксели, а
            # на этом сканере пустоты узкие и вреда от них меньше, чем от
            # повторного сжатия, которое после заливки становится
            # обязательным.
            tex = _fill_atlas_gaps(tex.convert("RGB"))
            touched = True

        # ПЕРЕЖИМАЕМ ТОЛЬКО ЕСЛИ ПРИШЛОСЬ ТРОГАТЬ ПИКСЕЛИ.
        #
        # Исходник от сканера уже JPEG. Если мы его не меняли, правильно
        # положить в GLB те же байты: повторное сжатие работает блоками 8x8 и
        # размазывает границы между фрагментами атласа — а фрагменты здесь
        # медианой 6.5 пикселя, то есть блок сжатия КРУПНЕЕ фрагмента. Отсюда
        # тёмные прожилки на десне, которых в файле сканера нет.
        if touched or img.format != "JPEG":
            import io
            buf = io.BytesIO()
            tex.convert("RGB").save(buf, format="JPEG", quality=TEX_QUALITY,
                                    optimize=True, subsampling=0)
            buf.seek(0)
            tex = Image.open(buf)
            tex.load()
            print(f"   текстура пережата (quality {TEX_QUALITY})")
        else:
            tex = img.convert("RGB") if img.mode != "RGB" else img
            print("   текстура из файла БЕЗ пережатия")

        # Геометрию НЕ упрощаем. Пробовал — с переносом UV ближайшей вершиной
        # модель покрылась чёрными пятнами: на швах развёртки соседняя
        # вершина несёт координаты из другой части текстуры, и цвет берётся
        # откуда попало.
        #
        # V НЕ инвертируем — это была причина «красных крапин» на зубах.
        # Инверсия нужна там, где текстура читается САМИМИ через numpy (ветка
        # запекания ниже): массив индексируется сверху вниз, UV снизу вверх.
        # В GLB координаты уходят как есть, glTF применяет конвенцию сам, и
        # наш переворот оказывался вторым подряд — выборка уезжала в
        # зеркальную по вертикали часть атласа. Замер связностью цвета у
        # соседних вершин: без инверсии среднее 5.8, с инверсией 12.6.
        uv = np.asarray(vis.uv, dtype=np.float64).copy()
        if UV_INSET_PX > 0:
            n_before = len(verts)
            verts, faces, uv = _inset_uv(verts, faces, uv, tex.size)
            print(f"   UV ужаты: вершин {n_before:,} -> {len(verts):,}")

        print(f"   текстура {img.size}, вершин {len(verts):,}, "
              f"граней {len(faces):,}")
        out = trimesh.Trimesh(verts, faces, process=False)
        mat = trimesh.visual.material.PBRMaterial(
            baseColorTexture=tex,
            # Слюна даёт блик, но зеркалом скан быть не должен: у зубов во
            # вьюере КЛКТ по той же причине metalness 0.
            metallicFactor=0.0, roughnessFactor=0.62)
        out.visual = trimesh.visual.TextureVisuals(uv=uv, material=mat)
        return out

    if img is None or vis.uv is None:
        print("   текстуры нет — оставляем серым")
        colors = np.full((len(verts), 3), 200, np.uint8)
    else:
        tex = np.asarray(img.convert("RGB"))
        h, w = tex.shape[:2]
        uv = np.asarray(vis.uv, np.float64)
        px = np.clip((uv[:, 0] * (w - 1)).round().astype(int), 0, w - 1)
        py = np.clip(((1.0 - uv[:, 1]) * (h - 1)).round().astype(int), 0, h - 1)
        colors = _face_average_colors(tex, np.asarray(vis.uv, np.float64), faces)
        print(f"   цвет усреднён по площади фрагментов {img.size}")
        # Второй шаг — выравнивание МЕЖДУ фрагментами. Первый шаг убирает шум
        # ВНУТРИ фрагмента, но соседние фрагменты сняты разными кадрами: на
        # зубах это незаметно, а на влажной десне вспышка даёт разброс яркости,
        # и она остаётся в бело-розовую крапинку. Один проход по соседям на
        # сетке снимает разницу между кадрами; больше нельзя — два прохода уже
        # стирают рисунок эмали и превращают зуб в пластик (проверено).
        # Выравнивание подсветки (`_flatten_shading`) НЕ применяем: замер
        # показал, что усиление до 1.7 загоняет красный канал в потолок 255 —
        # в файле не остаётся ни одной светлой вершины, десна краснеет.
        # Функция оставлена для сканов с настоящей неравномерностью света.
        # Билатеральный фильтр паутину НЕ берёт: её контраст 20-30 единиц, и
        # при любом разумном пороге он считает её границей ткани, а не шумом
        # (проверено на порогах 26 и 12 — картинка не изменилась). Обычное
        # усреднение по соседям её сглаживает, а настоящая граница зуб/десна
        # переживает: там контраст больше сотни и держится на многих вершинах.
        colors = _smooth_vertex_colors(colors, faces, len(verts), iters=5)
        print(f"   выровнены стыки кадров: {BILATERAL_ITERS} проходов "
              f"билатерально (порог {BILATERAL_SIGMA:.0f})")

    # Дубли вершин по швам развёртки: OBJ с текстурой хранит одну точку
    # несколько раз, поверхность топологически разрезана на 1205 кусков.
    # Упрощение такой сетки рвёт её по каждому шву — на модели это выглядело
    # как чёрные трещины по всей десне. Цвет уже снят, UV больше не нужны,
    # поэтому просто сливаем по координатам.
    key = np.round(verts, 5)
    _, first, inv = np.unique(key, axis=0, return_index=True,
                              return_inverse=True)
    if len(first) < len(verts):
        print(f"   слито дублей вершин: {len(verts) - len(first):,}")
        # ЦВЕТ СЛИВАЕМ УСРЕДНЕНИЕМ, А НЕ БЕРЁМ У ПЕРВОГО ДУБЛЯ.
        #
        # Это была причина «белой сетки» по десне, пережившей все прочие
        # правки. Дубль существует потому, что точка лежит НА ШВЕ развёртки:
        # у каждой копии свои UV, указывающие в РАЗНЫЕ фрагменты атласа.
        # `first` брал произвольную копию — и вдоль каждого шва цвет прыгал
        # на цвет соседнего куска. Швы образуют сетку по всей поверхности,
        # отсюда и рисунок: не пятна, а именно сетка.
        #
        # Среднее по копиям даёт на шве цвет обоих кусков сразу, то есть
        # ровно то, что видит глаз на настоящей поверхности.
        n_new = len(first)
        acc = np.zeros((n_new, 3), dtype=np.float64)
        cnt = np.zeros(n_new, dtype=np.float64)
        c_in = colors.astype(np.float64)
        for ch in range(3):
            acc[:, ch] = np.bincount(inv, weights=c_in[:, ch], minlength=n_new)
        cnt = np.bincount(inv, minlength=n_new).astype(np.float64)
        cnt[cnt == 0] = 1.0
        colors = np.clip(np.round(acc / cnt[:, None]), 0, 255).astype(np.uint8)
        verts, faces = verts[first], inv[faces]

    if len(faces) > JAW_FACES:
        import fast_simplification
        v2, f2 = fast_simplification.simplify(
            verts, faces, target_reduction=1.0 - JAW_FACES / len(faces))
        v2 = np.asarray(v2, np.float64)
        _, nn = cKDTree(verts).query(v2, k=1, workers=-1)
        verts, faces, colors = v2, np.asarray(f2, np.int64), colors[nn]

    out = trimesh.Trimesh(verts, faces, process=False)
    out.visual = trimesh.visual.ColorVisuals(mesh=out, vertex_colors=colors)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--upper")
    ap.add_argument("--lower")
    ap.add_argument("--out", required=True)
    ap.add_argument("--fill-gaps", action="store_true",
                    help="залить пустоты атласа (меняет пиксели и требует "
                         "пережатия — по умолчанию выключено)")
    ap.add_argument("--baked", action="store_true",
                    help="цвет в вершины вместо текстуры (запасной режим)")
    args = ap.parse_args()

    scene = trimesh.Scene()
    for jaw, path in (("upper", args.upper), ("lower", args.lower)):
        if not path:
            continue
        m = load_jaw(Path(path), baked=args.baked,
                     fill_gaps=args.fill_gaps)
        # тот же разворот осей, что в ios_build_mesh, чтобы сцены совпадали
        m.vertices = to_viewer_axes(m.vertices)
        scene.add_geometry(m, geom_name=f"raw_{jaw}")
        print(f"{jaw}: вершин={len(m.vertices):,} граней={len(m.faces):,}")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(trimesh.exchange.gltf.export_glb(scene))
    print(f"\n{out.name}: {out.stat().st_size / 1e6:.2f} МБ")


if __name__ == "__main__":
    main()
