# Текстуру сканера УМЕНЬШАТЬ НЕЛЬЗЯ, и это главное здесь.
#
# Врач с приёма: «это не оригинал» — и был прав: цвет, запечённый в вершины,
# несёт ровно столько деталей, сколько вершин, и налёт с границами пломб
