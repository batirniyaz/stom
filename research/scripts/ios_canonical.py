"""Приведение интраорального скана к ориентации, на которой обучалась модель.

Teeth3DS хранит верхнюю челюсть коронками ВВЕРХ (как она лежит на столе у
сканера), а Bits2Bites и Exocad — анатомически, коронками вниз. Разница 180°,
а аугментация поворотами при обучении узкая (+-20°, шире нельзя: сеть
перестанет отличать левое от правого). На перевёрнутой дуге нумерация
рассыпается: центральный резец пропадает на всех 25 проверенных сканах.

Определять верх геометрией ненадёжно, поэтому судьёй выступает сама сеть:
прогоняем четыре разворота на 180° вокруг осей (это все повороты, сохраняющие
хиральность — отражать нельзя, лево и право поменяются местами) и берём тот,
где зубы складываются в связную дугу.

Использование:
    from ios_canonical import canonical_transform
    R = canonical_transform(model, pts, nrm, device, chunk)
    pts, nrm = pts @ R.T, nrm @ R.T
"""

import numpy as np

# Повороты на 180° вокруг осей x, y, z плюс тождественный. Определитель +1
# у всех четырёх, отражений здесь нет.
#
# ЭТОГО НАБОРА МАЛО, и это выяснилось на чужих данных. Он покрывает только
# случаи, когда вертикаль скана уже совпадает с осью Z. У сканов figshare
# 26965903 вертикаль лежит по оси Y, то есть нужен поворот на 90°, которого
# в списке нет: канонизация выбирала лучший из четырёх заведомо неверных
# вариантов и молча возвращала мусор. Симптом — у каждого скана СВОЯ
# произвольная ориентация (замер «резцы минус моляры»: ось 2 у нашего,
# ось 0 и ось 1 у чужих), стороны зеркальны, верх с низом переставлены.
CANDIDATES = [
    ("как есть", np.diag([1.0, 1.0, 1.0])),
    ("разворот вокруг X", np.diag([1.0, -1.0, -1.0])),
    ("разворот вокруг Y", np.diag([-1.0, 1.0, -1.0])),
    ("разворот вокруг Z", np.diag([-1.0, -1.0, 1.0])),
]


def vertical_axis(pts) -> int:
    """Какая ось у челюсти вертикальная — по габариту.

    Челюсть плоская: вдоль дуги и поперёк неё она в два-три раза шире, чем в
    высоту. Замер по 16 сканам датасета и нашему клиническому: доля короткой
    оси от средней — медиана 0.40, максимум 0.64, и ни разу короткой не
    оказалась не-вертикальная ось. Это дешевле и надёжнее, чем угадывать
    вертикаль прогонами сети.
    """
    ext = np.asarray(pts).max(axis=0) - np.asarray(pts).min(axis=0)
    return int(np.argmin(ext))


def axis_candidates(vert_axis: int):
    """Все повороты, ставящие заданную ось вертикально. Отражений нет.

    Восемь штук: два знака вертикали на четыре поворота вокруг неё. Вместе с
    выбором оси это покрывает любую ориентацию, выровненную по осям, — то
    есть все, какие встречаются у сканеров.
    """
    out = []
    others = [i for i in range(3) if i != vert_axis]
    for sz in (1.0, -1.0):
        ez = np.zeros(3)
        ez[vert_axis] = sz
        ex0 = np.zeros(3)
        ex0[others[0]] = 1.0
        ey0 = np.cross(ez, ex0)          # правая тройка по построению
        for k in range(4):
            ang = k * np.pi / 2
            ex = np.cos(ang) * ex0 + np.sin(ang) * ey0
            ey = np.cross(ez, ex)
            R = np.array([ex, ey, ez])
            # Страховка от опечатки: отражение здесь недопустимо, оно меняет
            # лево и право местами. Проект на этом уже терял сторону дважды.
            if np.linalg.det(R) < 0:
                raise RuntimeError("кандидат оказался отражением")
            out.append((f"вертикаль=ось {vert_axis}{'+' if sz > 0 else '-'}, "
                        f"поворот {k * 90}°", R))
    return out


def arch_score(pts_mm, labels, n_classes=17, min_pts=30):
    """Насколько предсказание похоже на настоящую зубную дугу.

    Считаем зубы и нарушения порядка их следования вдоль дуги. У правильной
    ориентации зубов много и порядок не рвётся; у перевёрнутой — наоборот.
    """
    cents = {}
    for c in range(1, n_classes):
        m = labels == c
        if m.sum() >= min_pts:
            cents[c] = pts_mm[m].mean(axis=0)
    if len(cents) < 4:
        return -1e9, len(cents), 0
    arr = np.array(list(cents.values()))
    ctr = arr[:, :2].mean(axis=0)
    ang = {c: np.arctan2(v[1] - ctr[1], v[0] - ctr[0]) for c, v in cents.items()}
    order = sorted(ang, key=lambda c: ang[c])
    lin = [(9 - c) if c <= 8 else c for c in order]
    n = len(lin)
    inv = min(min(sum(1 for a, b in zip(r, r[1:]) if b < a),
                  sum(1 for a, b in zip(r, r[1:]) if b > a))
              for r in (lin[s:] + lin[:s] for s in range(n)))
    return len(cents) - 3.0 * inv, len(cents), inv


# Эталон снят с обучающих данных (12 сканов каждой челюсти, единогласно):
# коронки лежат ВЫШЕ десны, а номера зубов обходят дугу в строго определённую
# сторону. Знак обхода — единственный признак, различающий разворот вокруг X
# и вокруг Y: оба ставят коронки вверх, но второй меняет лево и право
# местами, а связность дуги к этому слепа.
REF_CHIRALITY = {"upper": -1.0, "lower": +1.0}


def chirality(pts_mm, labels, n_classes=17, min_pts=30):
    """Знак обхода дуги при возрастании номера позиции, вид со стороны +z."""
    cents = {}
    for c in range(1, n_classes):
        m = labels == c
        if m.sum() >= min_pts:
            cents[c] = pts_mm[m].mean(axis=0)
    if len(cents) < 6:
        return 0.0
    ctr = np.array(list(cents.values()))[:, :2].mean(axis=0)
    items = sorted(((9 - c) if c <= 8 else c, v) for c, v in cents.items())
    ang = np.unwrap([np.arctan2(v[1] - ctr[1], v[0] - ctr[0]) for _, v in items])
    return float(np.sign(ang[-1] - ang[0]))


# Признак, различающий ПОВОРОТ ВОКРУГ ВЕРТИКАЛИ. Ни `arch_score`, ни
# `chirality` его не ловят: дуга при таком повороте остаётся дугой и обход не
# меняет знак. Из равноценных кандидатов выбирался произвольный — у верхней
# челюсти pair001 два варианта разошлись на 1 балл, и победил зеркальный: все
# 13 верхних зубов встали на чужую сторону при верной нижней.
#
# ДВЕ ПОПЫТКИ, КОТОРЫЕ ПРОВАЛИЛИСЬ, и обе по одной причине — они опирались на
# МЕТКИ СЕТИ, а сеть переприсваивает их под каждый поворот заново:
#   * направление «от центра дуги к резцам»: сеть метит резцами то, что сама
#     считает передом, поэтому вектор указывал верно при любом повороте
#     (замер: +0.91..+1.00 у всех восьми кандидатов);
#   * отношение размеров «задние зубы к передним»: сеть всегда метит молярами
#     крупные, поэтому отношение держалось около 1.67 независимо от поворота.
#
# Работает только признак, ВООБЩЕ не касающийся меток: подкова открыта назад.
# Асимметрия облака точек вдоль оси «перед-зад» положительна у 100% из 60
# проверенных сканов Teeth3DS (медиана +0.23, разброс +0.05..+0.40), а самый
# пустой сектор по углу смотрит в +Y у 100% из них (медиана +98°).
ARCH_SKEW_MIN = 0.0


def arch_opening(pts) -> float:
    """Асимметрия облака вдоль оси Y. >0 — подкова открыта в сторону +Y.

    Считается по ВСЕМ точкам скана, без сегментации: именно поэтому признак и
    различает повороты, к которым метки сети слепы.
    """
    p = np.asarray(pts, dtype=float)
    y = p[:, 1] - p[:, 1].mean()
    sd = float(y.std())
    if sd <= 1e-9:
        return 0.0
    return float((y ** 3).mean() / sd ** 3)


def crowns_up(pts_mm, labels):
    """Коронки выше десны? В обучающих данных так у обеих челюстей."""
    t, g = labels > 0, labels == 0
    if t.sum() < 100 or g.sum() < 100:
        return False
    return pts_mm[t, 2].mean() > pts_mm[g, 2].mean()


def canonical_transform(model, pts, nrm, device, chunk, jaw="upper",
                        scale_mm=50.0, verbose=False):
    """-> матрица 3x3, приводящая скан к ориентации обучающих данных."""
    from ios_seg_eval import predict_scan
    # Кандидаты строятся вокруг ГЕОМЕТРИЧЕСКИ найденной вертикали, а не
    # вокруг предположения, что она уже по Z.
    cands = axis_candidates(vertical_axis(pts))
    # Геометрический отсев ДО прогона сети: он вдвое дешевле и снимает ровно
    # ту неоднозначность, которую метки не различают.
    kept = [(nm, R) for nm, R in cands
            if arch_opening(pts @ R.T) > ARCH_SKEW_MIN]
    if kept:
        cands = kept
    best, best_R = None, cands[0][1]
    for name, R in cands:
        p = (pts @ R.T).astype(np.float32)
        n = (nrm @ R.T).astype(np.float32)
        lab = predict_scan(model, p, n, device, chunk=chunk)
        mm = p * scale_mm
        score, n_teeth, inv = arch_score(mm, lab)
        up = crowns_up(mm, lab)
        ch = chirality(mm, lab)
        skew = arch_opening(p)
        ok = up and ch == REF_CHIRALITY.get(jaw, -1.0)
        if not ok:
            score -= 100.0          # не отбрасываем совсем: вдруг все плохи
        if verbose:
            print(f"   {name:<34} зубов={n_teeth:>2} нарушений={inv:>2} "
                  f"коронки_вверх={'да' if up else 'нет':<3} обход={ch:+.0f} "
                  f"подкова={skew:+.2f} оценка={score:>7.1f}"
                  f"{'  <-- выбран' if best is None or score > best else ''}")
        if best is None or score > best:
            best, best_R = score, R
    return best_R


# ================= экспорт во вьюер =================

def to_viewer_axes(verts):
    """Оси сканера (вверх Z) -> оси three.js (вверх Y). Поворот, НЕ отражение.

    Очевидная на вид перестановка (x, y, z) -> (x, z, y) — это транспозиция
    двух осей: определитель -1, то есть зеркало. Модель уезжает в отражение,
    лево и право меняются местами (зуб 11 встаёт на место левого резца), а
    нормали выворачиваются внутрь. Замер на скане клиники: объём +5983 мм³
    до перестановки и -5983 мм³ после. Во вьюере это не бросается в глаза,
    потому что материалы стоят DoubleSide. Правильный перевод Z-up -> Y-up
    отличается знаком: (x, z, -y), определитель +1.

    В КЛКТ тот же перевод сделан перестановкой [2, 0, 1] — она циклическая,
    определитель +1, и там ошибки нет. Сравнивать надо именно определитель:
    на глаз обе перестановки выглядят одинаково безобидно.

    Передний отдел после поворота смотрит в +Z, то есть в камеру вьюера: врач
    видит пациента спереди, и правая сторона пациента (квадранты 1 и 4)
    оказывается СЛЕВА на экране — та же конвенция, что на ОПТГ. Проверено на
    скане Exocad; если другой сканер отдаст оси иначе, развернётся вид по
    умолчанию, но зеркала уже не будет ни при каких осях.
    """
    v = np.asarray(verts, dtype=np.float64)
    return np.column_stack([v[:, 0], v[:, 2], -v[:, 1]])
