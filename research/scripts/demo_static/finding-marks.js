/* Цвет и подпись по ТИПУ находки — один справочник на весь продукт.
 *
 * Зачем файлом, а не константой в каждом экране. Этими цветами красятся
 * значки на зубной карте в разборе, легенда под ней и зубы на заставке.
 * Пока список лежал внутри `index.html`, заставка не могла им
 * воспользоваться — и либо осталась бы без цвета, либо завела бы свои
 * цвета, которые разошлись бы с картой при первой же правке. В этом
 * проекте так уже было со справочником ролей и с палитрой уровней.
 *
 * ПОРЯДОК ЗНАЧИМ. У зуба бывает несколько находок сразу (пломбированный
 * канал и близость к пазухе), а цвет у него один. Берём ПЕРВЫЙ
 * подходящий сверху — список отсортирован по тому, насколько находка
 * меняет решение врача: лечение канала важнее соседства с пазухой,
 * которое само по себе норма.
 *
 * Чего здесь НЕТ: уровня важности. Он живёт отдельно (clinic_routes.LEVELS
 * на сервере, `--lv-*` в палитре) и отвечает на другой вопрос — не «что
 * нашли», а «насколько это срочно». Смешивать их в один цвет нельзя:
 * «близко к каналу» бывает и тревогой, и предупреждением.
 */
(function () {
  const MARKS = [
    ["endo_filled",     "#f43f5e", "канал пломбирован"],
    ["tooth_impacted",  "#a78bfa", "ретенция"],
    ["canal_contact",   "#ef4444", "близко к каналу"],
    ["canal_close",     "#ef4444", "близко к каналу"],
    ["bone_loss",       "#f59e0b", "уровень кости"],
    ["restoration",     "#cbd5e1", "реставрация"],
    ["sinus_contact",   "#56b8d6", "близко к пазухе"],
    ["sinus_close",     "#56b8d6", "близко к пазухе"],
  ];

  const BY_CODE = {};
  for (const [code, color, label] of MARKS) BY_CODE[code] = { color, label };

  /** Цвет и подпись по списку кодов находок зуба. null — красить нечем. */
  function markOf(codes) {
    if (!codes || !codes.length) return null;
    const has = new Set(codes);
    for (const [code, color, label] of MARKS) {
      if (has.has(code)) return { code, color, label };
    }
    return null;
  }

  /** Легенда: по одной записи на ПОДПИСЬ, а не на код. Два кода с одной
      подписью («близко к каналу» это contact и close) дали бы две
      одинаковые строки. */
  function legend(codes) {
    const want = codes ? new Set(codes) : null;
    const out = [], seen = new Set();
    for (const [code, color, label] of MARKS) {
      if (want && !want.has(code)) continue;
      if (seen.has(label)) continue;
      seen.add(label);
      out.push({ color, label });
    }
    return out;
  }

  window.findingMarks = { MARKS, BY_CODE, markOf, legend };
})();
