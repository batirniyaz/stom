/* Тип зуба по номеру FDI: резец, клык, премоляр, моляр.
 *
 * Зачем отдельным файлом. Этой раскраской пользуются и заставка, и панель
 * сцены в разборе. Константа внутри одного экрана означала бы, что на
 * первом экране премоляр одного цвета, а в разборе другого, — а цвет здесь
 * и есть всё сообщение.
 *
 * Тип читается из ВТОРОЙ цифры номера: 11–18 это верхняя правая челюсть,
 * где 1 и 2 резцы, 3 клык, 4 и 5 премоляры, 6–8 моляры. Система FDI
 * устроена так во всех четырёх квадрантах, поэтому квадрант можно
 * отбросить — что и делаем.
 *
 * Цвета взяты из макета, чтобы продукт и прототип не разъезжались.
 */
(function () {
  const TYPES = [
    { key: "incisor",   label: "резцы",     color: "#8fd3c8", pos: [1, 2] },
    { key: "canine",    label: "клыки",     color: "#f2c26b", pos: [3] },
    { key: "premolar",  label: "премоляры", color: "#9db7ff", pos: [4, 5] },
    { key: "molar",     label: "моляры",    color: "#e59ad0", pos: [6, 7, 8] },
  ];

  const BY_POS = {};
  for (const t of TYPES) for (const p of t.pos) BY_POS[p] = t;

  /** Тип зуба по номеру FDI. null — номер не похож на зуб. */
  function typeOf(fdi) {
    const n = parseInt(fdi, 10);
    if (!n || n < 11 || n > 48) return null;
    return BY_POS[n % 10] || null;
  }

  window.toothTypes = { TYPES, typeOf };
})();
